/**
 * Build hreflang link objects for react-helmet-async.
 * Returns self-referencing `en` + `x-default` tags for the given canonical URL.
 * Important for dental tourism SEO — signals Google that the page targets English-speaking patients globally.
 */
export function buildHreflangTags(canonicalUrl: string) {
  return [
    { rel: 'alternate', hrefLang: 'en', href: canonicalUrl },
    { rel: 'alternate', hrefLang: 'x-default', href: canonicalUrl },
  ];
}

export function buildDentalTourismHreflangTags(canonicalUrl: string) {
  const countryCluster = [
    { rel: 'alternate', hrefLang: 'en', href: SEO.dentalTourism.canonical },
    { rel: 'alternate', hrefLang: 'en-AE', href: SEO.dentalTourismUae.canonical },
    { rel: 'alternate', hrefLang: 'en-SA', href: SEO.dentalTourismSaudi.canonical },
    { rel: 'alternate', hrefLang: 'en-KW', href: SEO.dentalTourismKuwait.canonical },
    { rel: 'alternate', hrefLang: 'en-QA', href: SEO.dentalTourismQatar.canonical },
    { rel: 'alternate', hrefLang: 'en-OM', href: SEO.dentalTourismOman.canonical },
    { rel: 'alternate', hrefLang: 'en-BH', href: SEO.dentalTourismBahrain.canonical },
    { rel: 'alternate', hrefLang: 'en-GB', href: SEO.dentalTourismUk.canonical },
    { rel: 'alternate', hrefLang: 'en-DE', href: SEO.dentalTourismGermany.canonical },
    { rel: 'alternate', hrefLang: 'x-default', href: SEO.dentalTourism.canonical },
  ];

  const clusteredCanonicals = new Set(countryCluster.map((tag) => tag.href));
  if (!clusteredCanonicals.has(canonicalUrl)) {
    return buildHreflangTags(canonicalUrl);
  }

  return countryCluster;
}
